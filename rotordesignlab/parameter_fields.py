def label(key):return FIELDS.get(key,(key,''))[0]
def help_text(key):return FIELDS.get(key,('', ''))[1]
def location(path):
    return ' / '.join(f'第{key+1}项' if isinstance(key,int) else label(key) for key in path) or '方案'


def schema_message(error):
    rule=error.validator;value=error.validator_value
    if rule=='required':return '待填写：'+'、'.join(label(k) for k in value if k not in error.instance)
    if rule=='type':return '请填写'+{'number':'有限数值','integer':'整数','string':'文字','array':'完整表格','object':'参数组','boolean':'是/否选项'}.get(value,'有效值')
    if rule in ('minimum','exclusiveMinimum','maximum','exclusiveMaximum'):
        return {'minimum':'不得小于','exclusiveMinimum':'必须大于','maximum':'不得大于','exclusiveMaximum':'必须小于'}[rule]+str(value)
    if rule in ('minItems','maxItems'):return f'表格长度要求：{value}项（请检查是否缺行或多行）'
    if rule in ('minLength','pattern'):return '文字为空或格式不符合要求'
    if rule=='enum':return '请选择提供的选项'
    if rule=='oneOf':return '需提供且仅提供一种翼型数据表'
    return '格式不符合机型定义：'+str(rule)
